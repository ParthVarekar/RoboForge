const TILDE = [0x08, 0x04, 0x08, 0x10, 0x08];
const ARROW_RIGHT = [0x08, 0x08, 0x2a, 0x1c, 0x08];
const ARROW_LEFT = [0x08, 0x1c, 0x2a, 0x08, 0x08];
const MISSING = [0x7f, 0x41, 0x41, 0x41, 0x7f];

function ascii(code: number): readonly number[] | null {
  if (code < 0x20 || code > 0x7d) return null;
  const i = (code - 0x20) * 5;
  return ASCII.slice(i, i + 5);
}

