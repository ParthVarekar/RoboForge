const lcdCache = new Map<number, Uint8Array>();

/**
 * The eight pixel rows (5-bit masks, bit 4 = left column) of an HD44780 ROM character. Codes 0x80-0xA0 are blank in
 * the A00 ROM; katakana are not drawn here and show as a hollow box.
 */
export function lcdGlyphRows(code: number): Uint8Array {
  const c = code & 0xff;
  const hit = lcdCache.get(c);
  if (hit) return hit;
  const blank = c === 0x20 || (c >= 0x80 && c <= 0xa0);
  const cols = blank ? [0, 0, 0, 0, 0] : (A00_EXTRA[c] ?? ascii(c) ?? MISSING);
  const rows = new Uint8Array(8);
  for (let r = 0; r < 8; r += 1) {
    let mask = 0;
    for (let x = 0; x < 5; x += 1) if (((cols[x] ?? 0) >> r) & 1) mask |= 1 << (4 - x);
    rows[r] = mask;
  }
  lcdCache.set(c, rows);
  return rows;
}
