/**
 * Column bytes of a character in the Adafruit_GFX built-in font (code page 437 numbering). The caller applies the
 * library's `cp437(false)` quirk (codes 176 and up shifted by one) before asking.
 */
export function gfxGlyph(code: number): readonly number[] {
  const c = code & 0xff;
  return CP437_EXTRA[c] ?? ascii(c) ?? (c === 0x20 ? [0, 0, 0, 0, 0] : MISSING);
}

