"""Turns a video you have into an Arduino sketch that plays it on the 128x64 SSD1306 OLED.

Usage:  python scripts/tools/video_to_oled.py my_video.mp4 out.ino [--fps 10] [--seconds 30] [--sda 21 --scl 22]
Needs ffmpeg on PATH and Pillow. Each frame is 1 KB (128x64, 1 bit), so keep it short: 30 s at 10 fps is 300 KB,
which fits an ESP32's flash and stays usable in the editor. Paste out.ino into the Code tab, or upload it to a board.
"""
import argparse, io, subprocess, sys
from PIL import Image

p = argparse.ArgumentParser()
p.add_argument('video'); p.add_argument('out')
p.add_argument('--fps', type=float, default=10); p.add_argument('--seconds', type=float, default=30)
p.add_argument('--sda', type=int, default=21); p.add_argument('--scl', type=int, default=22)
a = p.parse_args()

raw = subprocess.run(['ffmpeg', '-v', 'error', '-t', str(a.seconds), '-i', a.video, '-vf',
                      f'fps={a.fps},scale=128:64:force_original_aspect_ratio=decrease,pad=128:64:(ow-iw)/2:(oh-ih)/2',
                      '-f', 'image2pipe', '-vcodec', 'png', '-'], capture_output=True, check=True).stdout
frames, i = [], 0
while (j := raw.find(b'\x89PNG', i + 1)) != -1 or i < len(raw):
    chunk = raw[i:j] if j != -1 else raw[i:]
    if chunk.startswith(b'\x89PNG'):
        im = Image.open(io.BytesIO(chunk)).convert('L')
        bits = []
        for y in range(64):
            for xb in range(16):
                v = 0
                for k in range(8):
                    if im.getpixel((xb * 8 + k, y)) > 127: v |= 0x80 >> k
                bits.append(v)
        frames.append(bits)
    if j == -1: break
    i = j
if not frames: sys.exit('no frames decoded')

with open(a.out, 'w') as f:
    f.write('// Video on the SSD1306 OLED, generated by scripts/tools/video_to_oled.py\n')
    f.write('#include <Wire.h>\n#include <Adafruit_GFX.h>\n#include <Adafruit_SSD1306.h>\n\n')
    f.write('Adafruit_SSD1306 display(128, 64, &Wire, -1);\n')
    f.write(f'const int FRAMES = {len(frames)};\nconst int FRAME_MS = {round(1000 / a.fps)};\n')
    f.write('static const unsigned char PROGMEM video[] = {\n')
    for fr in frames: f.write('  ' + ', '.join(f'0x{b:02X}' for b in fr) + ',\n')
    f.write('};\n\nint frame = 0;\nunsigned long nextAt = 0;\n\n')
    f.write(f'void setup() {{\n  Wire.begin({a.sda}, {a.scl});\n  display.begin(SSD1306_SWITCHCAPVCC, 0x3C);\n}}\n\n')
    f.write('void loop() {\n  if (millis() < nextAt) { delay(1); return; }\n  nextAt = millis() + FRAME_MS;\n'
            '  display.clearDisplay();\n'
            '  for (int y = 0; y < 64; y++) {\n    for (int xb = 0; xb < 16; xb++) {\n'
            '      int b = video[frame * 1024 + y * 16 + xb];\n'
            '      for (int k = 0; k < 8; k++) if (b & (0x80 >> k)) display.drawPixel(xb * 8 + k, y, SSD1306_WHITE);\n'
            '    }\n  }\n  display.display();\n  frame = (frame + 1) % FRAMES;\n}\n')
print(f'{len(frames)} frames -> {a.out}')
